const fs = require('node:fs'), ts = require('typescript'), assert = require('node:assert/strict');
const fixture = { exports: {} };
const source = ts.transpileModule(fs.readFileSync('src/lib/workout-completion.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
new Function('module', 'exports', source)(fixture, fixture.exports);
const { toggleWorkoutExercise: toggle, undoRecordedSession: undo } = fixture.exports;
const date = '2026-11-12';
const exercise = slug => ({ slug, name: slug, level: 'beginner', primaryMuscles: [], category: 'strength', equipment: null, thumbUrl: null });
const exercises = ['press', 'fly'].map(exercise);
const other = { id: 'other-history', workoutId: 'other', workoutName: 'Other', completedAt: date, exercises: [] };
const base = { favourites: [], workouts: [{ id: 'chest', name: 'Chest', exercises }], progress: {}, sessionLog: { [date]: ['other'] }, completions: { [date]: 1 }, workoutHistory: { [date]: [other], '2026-11-11': [other] }, notes: { press: 'Keep my note' }, weeklySchedule: '' };
const click = (state, slug) => toggle(state, 'chest', slug, date, 'snapshot', date + 'T12:00:00Z');
let state = click(base, 'press');
assert.deepEqual(state.progress.chest, ['press']);
state = click(state, 'fly');
assert.equal(state.completions[date], 2);
assert.equal(state.workoutHistory[date].length, 2);
const completed = state;
state = click(state, 'press');
assert.deepEqual(state.progress.chest, ['fly'], 'Unticking restores the other completed exercise');
assert.deepEqual(state.sessionLog[date], ['other']);
assert.equal(state.completions[date], 1);
assert.deepEqual(state.workoutHistory[date], [other]);
assert.deepEqual(state.workoutHistory['2026-11-11'], base.workoutHistory['2026-11-11']);
assert.deepEqual(state.notes, base.notes);
state = click(state, 'press');
assert.equal(state.completions[date], 2, 'Rechecking records exactly one session');
assert.equal(state.workoutHistory[date].length, 2);
assert.deepEqual(undo(completed, 'chest', date).progress.chest, ['press', 'fly']);
const partial = { ...completed, workoutHistory: { ...completed.workoutHistory, [date]: [other, { ...completed.workoutHistory[date][1], exercises: [exercises[0]] }] } };
assert.deepEqual(click(partial, 'press').progress.chest, [], 'A partial recorded selection can be unticked');
assert.equal(click(partial, 'fly').workoutHistory[date].length, 2, 'Adding the final missing exercise replaces the recorded snapshot');
const single = { ...base, workouts: [{ id: 'chest', name: 'Single', exercises: [exercises[0]] }] };
assert.deepEqual(click(click(single, 'press'), 'press').progress.chest, []);
assert.equal(toggle(base, 'missing', 'press', date, 'id', date), base);
assert.deepEqual(base.progress, {}, 'Original snapshots are not mutated');
console.log('PASS: complete/untick/recheck, partial and single-exercise sessions, history/heatmap consistency, other sessions and notes preserved.');
